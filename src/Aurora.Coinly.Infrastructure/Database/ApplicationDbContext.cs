using Aurora.Coinly.Application.Abstractions.Data;
using Aurora.Coinly.Domain.Budgets;
using Aurora.Coinly.Domain.Categories;
using Aurora.Coinly.Domain.Methods;
using Aurora.Coinly.Domain.Summary;
using Aurora.Coinly.Domain.Transactions;
using Aurora.Coinly.Domain.Users;
using Aurora.Coinly.Domain.Wallets;
using Microsoft.EntityFrameworkCore.Metadata;

namespace Aurora.Coinly.Infrastructure.Database;

public sealed class ApplicationDbContext(
    DbContextOptions<ApplicationDbContext> options) : DbContext(options), ICoinlyDbContext
{
    internal const string DEFAULT_SCHEMA = "coinly";

    public DbSet<Budget> Budgets { get; set; } = null!;
    public DbSet<BudgetPeriod> BudgetPeriods { get; set; } = null!;
    public DbSet<BudgetTransaction> BudgetTransactions { get; set; } = null!;
    public DbSet<Category> Categories { get; set; } = null!;
    public DbSet<MonthlySummary> MonthlySummaries { get; set; } = null!;
    public DbSet<PaymentMethod> PaymentMethods { get; set; } = null!;
    public DbSet<Transaction> Transactions { get; set; } = null!;
    public DbSet<User> Users { get; set; } = null!;
    public DbSet<UserToken> UserTokens { get; set; } = null!;
    public DbSet<Wallet> Wallets { get; set; } = null!;
    public DbSet<WalletHistory> WalletHistories { get; set; } = null!;

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.HasDefaultSchema(DEFAULT_SCHEMA);
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(ApplicationDbContext).Assembly);

        // Guid keys are generated by the domain (BaseEntity / entity factories), never by the
        // store. Without this, EF's convention treats them as ValueGeneratedOnAdd and infers a
        // non-default key means the row already exists — so a new child added to a tracked
        // aggregate is tracked as Modified instead of Added, causing a DbUpdateConcurrencyException.
        foreach (IMutableEntityType entityType in modelBuilder.Model.GetEntityTypes())
        {
            IMutableKey? primaryKey = entityType.FindPrimaryKey();

            foreach (IMutableProperty keyProperty in primaryKey?.Properties ?? [])
            {
                if (keyProperty.ClrType == typeof(Guid))
                {
                    keyProperty.ValueGenerated = ValueGenerated.Never;
                }
            }
        }

        base.OnModelCreating(modelBuilder);
    }
}